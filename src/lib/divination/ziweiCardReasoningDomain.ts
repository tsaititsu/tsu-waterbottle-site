export type ZiweiMajorStarName = keyof typeof ziweiLoveMindConclusions

export function getZiweiLoveMindConclusion(
  cardName: string,
  position: "正位" | "反位",
) {
  const conclusion = ziweiLoveMindConclusions[cardName as ZiweiMajorStarName]

  if (!conclusion) {
    return position === "反位"
      ? "沒有心。對方目前沒有準備投入或推進這段關係，後續要看實際行動，不要替對方補答案。"
      : "目前看不出明確有心。請回到對方是否持續主動、願意說清楚與實際投入來判斷。"
  }

  return position === "正位" ? conclusion.upright : conclusion.reversed
}

const loveMindSystemContracts = Object.entries(ziweiLoveMindConclusions)
  .map(
    ([star, conclusion]) =>
      `- ${star}正位：${conclusion.upright}\n- ${star}反位：${conclusion.reversed}`,
  )
  .join("\n")

